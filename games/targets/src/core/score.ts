import { ROUND_MS } from './targets';

/**
 * Итоговый счёт целиком приходит из ядра (`TargetsGame.score`) — здесь только
 * границы для серверного антифрода. Клиент НИЧЕГО не начисляет: он лишь
 * отправляет число, а валидация и начисление баллов — на сервере.
 */

/** Максимум целей, которые ядро успевает зажечь за партию (темп 800→420 мс). */
export const MAX_TARGETS_PER_ROUND = 102;

/**
 * Практический потолок счёта для серверной проверки. Абсолютный теоретический
 * максимум (все цели мельчайшие, мгновенная реакция, серия ×5) ≈ 35 400;
 * 50 000 — запас на будущий ретюнинг темпа. Всё, что выше, сервер обязан
 * отклонить как невозможное.
 */
export const SCORE_CAP = 50_000;

/** Минимально возможная длительность честной партии (мс) — партия фиксированная. */
export const MIN_ROUND_MS = ROUND_MS - 1_500;

/** Санитайзер перед отправкой: целое, без NaN, в разумных границах. */
export function sanitizeScore(score: number): number {
  if (!Number.isFinite(score) || score <= 0) return 0;
  return Math.min(SCORE_CAP, Math.round(score));
}
