import { harderLevers, type LevelDef, type StarGoals } from '@gamewingo/game-progress';
import { MAX_GUESSES } from './locale';

/**
 * Лестница «5 букв»: пятнадцать уровней, три главы по пять.
 *
 * Словарь один — пятибуквенный, поэтому длину слова менять нельзя. Рычаги:
 * попытки (6 → 5), строгий режим, редкие слова и таймер. Попыток никогда не
 * меньше пяти, золото — за три попытки, подсветка клавиатуры есть всегда: иначе
 * верх лестницы держится на везении, а не на аккуратной игре (аудит T9). Поздняя
 * сложность — в самом слове (редкие буквы) и во времени, а не в отборе попыток.
 *
 * - Уровни 1–4 · шесть попыток: строгий режим, потом редкие слова, потом оба сразу.
 * - Уровни 5–8 · пять попыток: тот же цикл — новое ограничение на знакомой партии.
 * - Уровни 9–15 · на время: таймер 5:00 появляется на чистой партии, к нему по
 *   очереди добавляются строгий режим и редкие слова, затем таймер ужимается до 3:00.
 *
 * Правило каталога (docs/PROGRESSION.md): на каждом шаге жёстче ровно один рычаг,
 * остальные могут только смягчиться — так новое ограничение начинается на
 * знакомой партии, а не поверх всех прежних. Проверяется тестом.
 */

export interface SozParams {
  /** Сколько попыток даётся: шесть в начале лестницы, пять дальше — не меньше. */
  guesses: number;
  /**
   * Строгий режим: каждая догадка обязана учитывать уже открытые подсказки —
   * найденные буквы стоят на своих местах, а «жёлтые» присутствуют в слове.
   */
  strict: boolean;
  /**
   * Редкие слова: загадка берётся из поднабора ответов с редкими буквами
   * (`core/rare.ts`). Частые буквы первых ходов такие слова не открывают.
   */
  rare: boolean;
  /** Потолок времени на слово в секундах; 0 — без таймера. */
  timeLimitSec: number;
}

export type SozLevel = LevelDef<SozParams>;

/** Рычаги сложности и в какую сторону каждый делает уровень жёстче. */
export const LEVERS = {
  guesses: 'less',
  strict: 'more',
  rare: 'more',
  timeLimitSec: 'limit',
} as const;

/** [попыток, строгий, редкие, секунд, золото, серебро] — звёзды по использованным попыткам. */
const TABLE: Array<[number, boolean, boolean, number, number, number]> = [
  // Шесть попыток.
  [6, false, false, 0, 3, 5],
  [6, true, false, 0, 3, 5], //   строгий режим
  [6, false, true, 0, 3, 5], //   редкие слова (строгий снят)
  [6, true, true, 0, 3, 5], //    строгий режим к редким словам
  // Пять попыток.
  [5, false, false, 0, 3, 4], //  пять попыток на чистой партии
  [5, true, false, 0, 3, 4], //   строгий режим
  [5, false, true, 0, 3, 4], //   редкие слова (строгий снят)
  [5, true, true, 0, 3, 4], //    строгий режим к редким словам
  // На время.
  [5, false, false, 300, 3, 4], // таймер 5:00 на чистой партии
  [5, true, false, 300, 3, 4], // строгий режим
  [5, false, true, 300, 3, 4], // редкие слова (строгий снят)
  [5, true, true, 300, 3, 4], //  строгий режим к редким словам
  [5, true, true, 240, 3, 4], //  таймер 4:00
  [5, true, true, 210, 3, 4], //  таймер 3:30
  [5, true, true, 180, 3, 4], //  таймер 3:00 — финал
];

export const LADDER: readonly SozLevel[] = TABLE.map(
  ([guesses, strict, rare, timeLimitSec, gold, silver], i) => {
    const goals: StarGoals = { gold, silver };
    return { n: i + 1, params: { guesses, strict, rare, timeLimitSec }, goals };
  },
);

export const LADDER_SIZE = LADDER.length;

/** Уровень по номеру. Номер вне лестницы зажимается — реестр мог сохранить старое значение. */
export function levelAt(n: number): SozLevel {
  return LADDER[Math.min(LADDER_SIZE, Math.max(1, Math.round(n))) - 1];
}

/** Какой рычаг стал жёстче на уровне `n` по сравнению с предыдущим; на первом — никакой. */
export function newLever(n: number): keyof SozParams | null {
  if (n <= 1) return null;
  return harderLevers(levelAt(n - 1).params, levelAt(n).params, LEVERS)[0] ?? null;
}

/** Параметры слова дня: классические правила без ограничений лестницы. */
export const DAILY_PARAMS: SozParams = {
  guesses: MAX_GUESSES,
  strict: false,
  rare: false,
  timeLimitSec: 0,
};
